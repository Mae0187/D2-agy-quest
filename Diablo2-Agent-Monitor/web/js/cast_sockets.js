window.D2_CAST_SOCKETS = {
    DIR16_CLOCK_TO_DCC: [4, 8, 0, 9, 5, 10, 1, 11, 6, 12, 2, 13, 7, 14, 3, 15],

    /**
     * 依據 AGENT.md 第 14 節原廠標準：
     * 1. 統一以角色腳底接觸點 Y - 38px 為軀幹/胸膛發射基準高度
     * 2. 手部沿著 16 方向發射面向向外微幅 8~12px 偏轉，絕不飄移至頭頂 (Y - 80px) 或腳底 (Y - 0px)
     */
    getCastSocket(heroId, tier, clockDir) {
        const safeDir = (clockDir % 16 + 16) % 16;
        const deg = (90 + safeDir * 22.5) % 360;
        const rad = deg * Math.PI / 180;
        const dirX = Math.cos(rad);
        const dirY = Math.sin(rad);

        // 原廠標準：軀幹基準高度 Y - 38px，手部沿面向向外 8~12px 微調
        let handX = dirX * 12;
        let handY = -38 + dirY * 6;

        // 融合各職業專屬精細偏移微調
        const heroData = window.D2_CAST_DATA && window.D2_CAST_DATA[heroId];
        if (heroData) {
            const tierData = heroData[tier] || heroData['light'] || heroData['medium'] || Object.values(heroData)[0];
            if (tierData && tierData.castSockets) {
                const dccDir = this.DIR16_CLOCK_TO_DCC[safeDir] ?? 4;
                const rawSock = tierData.castSockets[dccDir];
                if (rawSock) {
                    handX += (rawSock[0] || 0) * 0.25; // 平滑微調，杜絕劇烈漂移
                }
            }
        }
        return { x: Math.round(handX), y: Math.round(handY) };
    },

    getReleaseFrame(heroId, tier) {
        const heroData = (window.D2_CAST_DATA && window.D2_CAST_DATA[heroId]) || (window.D2_CAST_DATA && window.D2_CAST_DATA['paladin']);
        if (!heroData) return 8;
        const tierData = heroData[tier] || heroData['light'] || heroData['medium'] || Object.values(heroData)[0];
        return tierData && tierData.releaseFrame != null ? tierData.releaseFrame : 8;
    }
};
